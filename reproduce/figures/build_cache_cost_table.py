"""Build Appendix J's context-length table from retained RTX 5080 timings.

Run from any directory with Python 3; no GPU or plotting dependencies required.
"""
import json
from pathlib import Path
from statistics import mean, median

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "inputs/paper/evidence"


def main():
    records = [json.loads(line) for line in
               (EVIDENCE / "cache_cost_5080_raw.jsonl").read_text().splitlines()]
    assert len(records) == 81
    assert {row["backend"] for row in records} == {"eager"}
    summaries = []
    for length in (128, 512, 1792):
        for count in (32, 128, 256):
            group = [row for row in records if row["source_tokens"] == length
                     and row["resume_tokens"] == count]
            ids = sorted({row["case_id"] for row in group})
            assert len(ids) == 3
            per_case = []
            for case_id in ids:
                repeats = [row for row in group if row["case_id"] == case_id]
                assert {row["repeat"] for row in repeats} == {0, 1, 2}
                per_case.append({
                    "case_id": case_id,
                    **{key: median(row[key] for row in repeats) for key in (
                        "rebuild_ms", "cached_resume_ms", "rebuild_plus_resume_ms")},
                })
            summaries.append({
                "context_tokens": length,
                "resume_tokens": count,
                "rebuild_ms": median(row["rebuild_ms"] for row in per_case),
                "cached_resume_ms": median(row["cached_resume_ms"] for row in per_case),
                "extra_time_percent": mean(
                    100 * (row["rebuild_plus_resume_ms"] / row["cached_resume_ms"] - 1)
                    for row in per_case),
                "per_case_medians": per_case,
            })
    (EVIDENCE / "cache_cost_5080_summary.json").write_text(
        json.dumps(summaries, indent=2) + "\n")
    lines = ["% Generated by figures/src/build_cache_cost_table.py; do not edit by hand."]
    for length in (128, 512, 1792):
        short = next(row for row in summaries if row["context_tokens"] == length
                     and row["resume_tokens"] == 32)
        long = next(row for row in summaries if row["context_tokens"] == length
                    and row["resume_tokens"] == 256)
        lines.append(
            f"{length:,} & {short['rebuild_ms']:.1f} & {short['cached_resume_ms']:.1f}"
            f" & {short['extra_time_percent']:.1f} & {long['extra_time_percent']:.1f}"
            + r" \\")
    header = r"""\begin{tabular}{rrrrr}
\toprule
Context & Rebuild & Cached continuation & \multicolumn{2}{c}{Extra time (\%)} \\
(tokens) & (ms) & 32 tokens (ms) & 32 tokens & 256 tokens \\
\midrule
"""
    footer = r"""\bottomrule
\end{tabular}
"""
    (EVIDENCE / "cache_cost_5080_table.tex").write_text(
        lines[0] + "\n" + header + "\n".join(lines[1:]) + "\n" + footer)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
